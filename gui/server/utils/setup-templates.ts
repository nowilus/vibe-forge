export interface GeneratedFile {
  path: string;
  content: string;
}

export function generateFiles(a: WizardAnswers): GeneratedFile[] {
  const files: GeneratedFile[] = [
    { path: "STATE.md", content: state(a) },
    { path: "CHANGELOG.md", content: changelog(a) },
    { path: "PROJECT_MAP.md", content: projectMap(a) },
    { path: "PRODUCT.md", content: product(a) },
    { path: "PROJECT_RULES.md", content: projectRules(a) },
    { path: "CODING_RULES.md", content: codingRules(a) },
    { path: "DESIGN.md", content: design(a) },
    { path: "CLIENT_DOCS.md", content: clientDocs(a) },
    { path: "RELEASE_NOTES.md", content: releaseNotes(a) },
    { path: "LESSONS.md", content: lessons(a) },
    { path: "DEPLOYMENT.md", content: deployment(a) },
    { path: "DATABASE.md", content: database(a) },
    { path: ".env.example", content: envExample(a) },
  ];

  if (a.tools.includes("claude-code")) {
    files.push({ path: "CLAUDE.md", content: claudeMd(a) });
  }
  if (a.tools.includes("cursor")) {
    files.push({ path: ".cursorrules", content: cursorrules(a) });
  }
  if (a.tools.includes("codex")) {
    files.push({ path: "AGENTS.md", content: agentsMd(a) });
  }

  return files;
}
