function projectRules(a: WizardAnswers): string {
  return `# Project rules

> Master source of truth. Agent-agnostic. All tool-specific rule files derive from this.
> Last generated: ${today()} by vibe-forge Setup Wizard.

## Project identity
- **Name:** ${a.projectName}
- **Stack:** ${a.stack}
- **Language policy:** Code comments in English. Documentation in ${a.language}.
- **TDD tier:** ${TDD_LABEL[a.tddTier]}
- **Deployment target:** ${a.deployment}

## Security non-negotiables (cannot be overridden)
- NEVER commit \`.env\` files to git.
- ALWAYS use parameterised queries — no string concatenation in SQL/queries.
- Validate ALL user input at system boundaries before processing.
- No hardcoded API keys, passwords, or tokens in source code.
- All authentication routes must be rate-limited.
- Error messages shown to users must not leak internal state, stack traces, or secrets.

## Testing policy
${TDD_RULE[a.tddTier]}

## Code quality rules
- Functions: < 50 lines. Split if larger.
- Files: < 800 lines. Extract modules if larger.
- No deep nesting (> 4 levels) — use early returns.
- Prefer immutable operations — create new objects, do not mutate.
- No hardcoded magic numbers — use named constants.
- No \`console.log\` in production code — use a proper logger.

## Naming conventions
- Variables and functions: camelCase
- Classes, interfaces, types, components: PascalCase
- Constants: UPPER_SNAKE_CASE
- Booleans: \`is\` / \`has\` / \`should\` / \`can\` prefix
- Custom hooks: \`use\` prefix

## Error handling
- Handle errors explicitly at every level — never swallow silently.
- Provide user-friendly messages in UI-facing code.
- Log detailed context on the server side.

## Documentation rules
- \`STATE.md\`: overwrite to reflect current truth only. No history here.
- \`CHANGELOG.md\`: append only. Every meaningful change gets one entry.
- \`PROJECT_MAP.md\`: keep updated with every structural change.
- \`LESSONS.md\`: append after every mistake correction.
`;
}

function codingRules(a: WizardAnswers): string {
  return `# Coding rules

> Extends PROJECT_RULES.md with stack-specific guidance.

## Stack
${a.stack}

## General principles
- KISS — prefer the simplest solution that works.
- DRY — extract repeated logic; avoid copy-paste drift.
- YAGNI — don't build for hypothetical future requirements.

## Error handling
\`\`\`
// WRONG — silently swallowed
try { ... } catch {}

// CORRECT — explicit handling with context
try { ... } catch (error) {
  logger.error("Operation failed", { error, context });
  throw new Error("User-friendly message");
}
\`\`\`

## Input validation
- Use schema-based validation (Zod, Yup, Pydantic, etc.) at every system boundary.
- Never trust external data — API responses, user input, file content.
- Fail fast with a clear error message.

## Comments
- Only comment WHY — never WHAT.
- Delete commented-out code; use git history instead.
- No multi-line docstrings on obvious functions.
`;
}

